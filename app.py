from pathlib import Path
import joblib
import pandas as pd
import streamlit as st
import matplotlib.pyplot as plt
from sklearn.metrics import (
    accuracy_score, roc_auc_score, precision_score, recall_score,
    f1_score, matthews_corrcoef, confusion_matrix, classification_report,
    ConfusionMatrixDisplay
)

ROOT = Path(__file__).resolve().parent
MODEL_DIR = ROOT / "model"

st.set_page_config(page_title="Dry Bean Classifier", page_icon="🫘", layout="wide")
st.title("Dry Bean Classification")
st.write("An interactive demonstration of five machine-learning classification models.")
st.caption("Dataset: UCI Dry Bean | Multiclass classification")

MODEL_FILES = {
    "Logistic Regression": "logistic_regression.joblib",
    "Decision Tree": "decision_tree.joblib",
    "K-Nearest Neighbors": "knearest_neighbors.joblib",
    "Gaussian Naive Bayes": "gaussian_naive_bayes.joblib",
    "Support Vector Machine": "support_vector_machine.joblib",
}

missing = [name for name, filename in MODEL_FILES.items() if not (MODEL_DIR / filename).exists()]
if missing:
    st.error("Trained model files are missing. First run `python train_models.py` in the project folder.")
    st.write("Missing models:", ", ".join(missing))
    st.stop()

st.subheader("1. Upload test data")
st.write("Upload the `test_data.csv` generated by `train_models.py`. It must contain the 16 feature columns and the target column `Class`.")
uploaded = st.file_uploader("Choose a test CSV file", type=["csv"])

if uploaded is None:
    st.info("Upload test_data.csv to evaluate a model.")
    st.stop()

try:
    data = pd.read_csv(uploaded)
except Exception as exc:
    st.error(f"Could not read the CSV: {exc}")
    st.stop()

if "Class" not in data.columns:
    st.error("The uploaded CSV must include the target column named `Class` for evaluation.")
    st.stop()

st.write("Preview of uploaded data")
st.dataframe(data.head(10), use_container_width=True)

model_name = st.selectbox("2. Select a classification model", list(MODEL_FILES.keys()))
bundle = joblib.load(MODEL_DIR / MODEL_FILES[model_name])
model = bundle["pipeline"]
feature_columns = bundle["feature_columns"]

missing_columns = [col for col in feature_columns if col not in data.columns]
if missing_columns:
    st.error("Your CSV is missing required feature columns: " + ", ".join(missing_columns))
    st.stop()

X_test = data[feature_columns].apply(pd.to_numeric, errors="coerce")
y_test = data["Class"].astype(str)

if X_test.empty:
    st.error("The uploaded CSV has no rows.")
    st.stop()

if st.button("Run evaluation", type="primary"):
    predictions = model.predict(X_test)
    classes = model.classes_
    scores = {
        "Accuracy": accuracy_score(y_test, predictions),
        "Precision": precision_score(y_test, predictions, average="weighted", zero_division=0),
        "Recall": recall_score(y_test, predictions, average="weighted", zero_division=0),
        "F1 Score": f1_score(y_test, predictions, average="weighted", zero_division=0),
        "MCC": matthews_corrcoef(y_test, predictions),
    }
    try:
        probabilities = model.predict_proba(X_test)
        scores["AUC (weighted OVR)"] = roc_auc_score(
            y_test, probabilities, labels=classes, multi_class="ovr", average="weighted"
        )
    except (ValueError, AttributeError):
        scores["AUC (weighted OVR)"] = None

    st.subheader("3. Evaluation metrics")
    cols = st.columns(3)
    for col, (label, value) in zip(cols * 2, scores.items()):
        shown = "Not defined" if value is None or pd.isna(value) else f"{value:.4f}"
        col.metric(label, shown)

    st.subheader("4. Confusion matrix")
    cm = confusion_matrix(y_test, predictions, labels=classes)
    fig, ax = plt.subplots(figsize=(9, 6))
    display = ConfusionMatrixDisplay(confusion_matrix=cm, display_labels=classes)
    display.plot(ax=ax, xticks_rotation=45, colorbar=False)
    ax.set_title(f"Confusion Matrix – {model_name}")
    fig.tight_layout()
    st.pyplot(fig)
    plt.close(fig)

    st.subheader("5. Classification report")
    report = classification_report(y_test, predictions, zero_division=0, output_dict=True)
    st.dataframe(pd.DataFrame(report).transpose().round(4), use_container_width=True)

    output = data.copy()
    output["Predicted_Class"] = predictions
    st.subheader("6. Predictions")
    st.dataframe(output.head(25), use_container_width=True)
    st.download_button(
        "Download predictions as CSV",
        output.to_csv(index=False).encode("utf-8"),
        file_name="dry_bean_predictions.csv",
        mime="text/csv"
    )
